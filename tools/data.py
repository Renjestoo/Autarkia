"""Generate Autarkia JSON resources into src/generated/resources and generated Java ids into src/generated/java.

Content definitions live in tools/content_*.py modules; this script only writes files. It wipes the generated
JSON folders first so removed content leaves no stale files, and checks every vanilla sound against the
26.3 asset index.
"""

import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import datagen
import sounds_spec

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "src" / "generated" / "resources"
GEN_JAVA = ROOT / "src" / "generated" / "java" / "dev" / "autarkia" / "registry"
ASSET_INDEX = Path(r"C:\Users\renat\curseforge\minecraft\Install\assets\indexes\34.json")
JSON_DIRS = ["assets/autarkia/blockstates", "assets/autarkia/models", "assets/autarkia/items", "assets/autarkia/lang",
             "assets/autarkia/equipment", "assets/autarkia/sounds.json", "data"]


def check_sounds():
    index = json.loads(ASSET_INDEX.read_text(encoding="utf-8"))["objects"]
    h = index["minecraft/sounds.json"]["hash"]
    events = json.loads((ASSET_INDEX.parent.parent / "objects" / h[:2] / h).read_text(encoding="utf-8"))
    missing = []
    for sid, (kind, sources, _, _) in sounds_spec.ALL.items():
        for s in sources:
            if kind == "file" and f"minecraft/sounds/{s}.ogg" not in index:
                missing.append((sid, s))
            if kind == "event" and s.split(":", 1)[1] not in events:
                missing.append((sid, s))
    if missing:
        raise SystemExit(f"missing vanilla sounds: {missing}")
    print(f"sounds: {len(sounds_spec.ALL)} events, all vanilla sources present")


def write_sounds():
    out = {}
    for sid, (kind, sources, pitch, volume) in sounds_spec.ALL.items():
        entries = []
        for s in sources:
            e = {"name": s if kind == "event" else f"minecraft:{s}", "pitch": pitch, "volume": volume}
            if kind == "event":
                e["type"] = "event"
            entries.append(e)
        out[sid] = {"sounds": entries, "subtitle": f"subtitles.autarkia.{sid}"}
        datagen.LANG[f"subtitles.autarkia.{sid}"] = sid.replace(".", " ").replace("_", " ").capitalize()
    datagen.write_json("assets/autarkia/sounds.json", out)


def write_sound_ids():
    GEN_JAVA.mkdir(parents=True, exist_ok=True)
    lines = ["package dev.autarkia.registry;", "", "/** Generated by tools/data.py from tools/sounds_spec.py. */",
             "public final class SoundIds {", "    public static final String[] NAMES = {"]
    lines += [f'        "{s}",' for s in sounds_spec.ALL]
    lines += ["    };", "", "    private SoundIds() {", "    }", "}", ""]
    (GEN_JAVA / "SoundIds.java").write_text("\n".join(lines), encoding="utf-8")


def main():
    print("phase 1: clean generated JSON")
    for d in JSON_DIRS:
        p = GEN / d
        if p.is_dir():
            shutil.rmtree(p)
        elif p.exists():
            p.unlink()
    print("phase 2: sounds")
    check_sounds()
    write_sounds()
    write_sound_ids()
    print("phase 3: content")
    datagen.generate_all()
    print("phase 4: lang")
    datagen.write_lang()
    print(f"done: {datagen.COUNT[0]} files written")


if __name__ == "__main__":
    main()
